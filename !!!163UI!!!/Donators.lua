        local name, realm = strsplit('-', players[index])
        if searchHighlight and searchHighlight == index then
            row.name:SetText("|cff00aaff" .. name .. "|r")
        elseif topNamesOrder[players[index]] then 
            row.name:SetText(DARKYELLOW_FONT_COLOR:WrapTextInColorCode(name)) 
        else 
            row.name:SetText(name) 
        end
        row.server:SetText(realm)
    end

    CoreUICreateHybridStep2(scroll, 0, 0, "TOPLEFT", "TOPLEFT", 0)

    f:Hide()

    collectgarbage()
    return f()
end

