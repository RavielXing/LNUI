    local lastSearchText = nil
    local lastFoundIndex = nil

    local function doSearch(findNext)
        local text = searchBox:GetText()
        if not text or text == "" or text == "搜索粉丝姓名..." then return end

        text = text:lower():gsub("^[ ]+", ""):gsub("[ ]+$", "")
        if text == "" then return end

        local startIndex = 1
        if findNext and lastSearchText == text and lastFoundIndex then
            startIndex = lastFoundIndex + 1
            if startIndex > #players then startIndex = 1 end
        else
            lastSearchText = text
        end

        local searchCount = 0
        local i = startIndex
        while searchCount < #players do
            local fullname = players[i]
            local name, realm = strsplit('-', fullname)
            local lowerName = name and name:lower() or ""
            local lowerRealm = realm and realm:lower() or ""
            local lowerFull = fullname:lower()

            if lowerName:find(text, 1, true) or lowerRealm:find(text, 1, true) or lowerFull:find(text, 1, true) then
                searchHighlight = i
                lastFoundIndex = i
                CoreUIScrollTo(f.scroll, i - 1)
                if f.scroll.update then f.scroll.update() end
                return
            end

            searchCount = searchCount + 1
            i = i + 1
            if i > #players then i = 1 end
        end

        searchHighlight = nil
        lastFoundIndex = nil
        if UIErrorsFrame and UIErrorsFrame.AddMessage then
            UIErrorsFrame:AddMessage("未找到匹配的粉丝: " .. text, 1.0, 0.2, 0.2, 1.0)
        end
    end

