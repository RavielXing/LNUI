function U1Donators:CreateFrame()
    local player_seen = {}

    -- 从 recentDonators 获取玩家
    for realm, allday in pairs(recentDonators) do
        local realm_clean = realm:gsub("%[.-%]", "")
        for _, player in ipairs({strsplit(',', allday)}) do
            if player ~= "" then
                local fullname = player .. '-' .. realm_clean
                if not player_seen[fullname] then
                    table.insert(players, fullname)
                    player_seen[fullname] = true
                end
            end
        end
    end
    recentDonators = nil

    -- 从 U1.historyDonators 获取玩家
    if U1.historyDonators then
        for realm, allday in pairs(U1.historyDonators) do
            local realm_clean = realm:gsub("%[.-%]", "")
            for _, player in ipairs({strsplit(',', allday)}) do
                if player ~= "" then
                    local fullname = player .. '-' .. realm_clean
                    if not player_seen[fullname] then
                        table.insert(players, fullname)
                        player_seen[fullname] = true
                    end
                end
            end
        end
        U1.historyDonators = nil
    end

    -- 从 afdianDonators 获取玩家
    for _, fullname in ipairs({ strsplit(',', afdianDonators) }) do
        if fullname ~= "" and not player_seen[fullname] then
            table.insert(players, fullname)
            player_seen[fullname] = true
        end
    end
    afdianDonators = nil

    player_seen = nil

    table.sort(players, function(a, b)
        local order1 = lastNamesOrder[a] or topNamesOrder[a] or 9999
        local order2 = lastNamesOrder[b] or topNamesOrder[b] or 9999
        if order1 ~= order2 then return order1 < order2 end
        local _, r1 = strsplit("-", a)
        local _, r2 = strsplit("-", b)
        if r1 ~= r2 then
            if r1 == '???' then return false
            elseif r2 == '???' then return true
            else return r1 < r2; end
        end
        return a < b
    end)
    -- 排完序就不需要了
    topNames = nil
    lastNamesOrder = nil

    local f = WW:Frame("U1DonatorsFrame", UIParent, "BasicFrameTemplateWithInset"):Size(320, 530):TR(U1Frame, "TL", -10, 0):SetToplevel(1):SetFrameStrata("DIALOG")

